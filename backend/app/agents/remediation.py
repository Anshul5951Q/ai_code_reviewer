"""
Remediation Agent.

Generates minimal, targeted, and framework-appropriate code fixes for detected
security vulnerabilities and quality issues without touching live repositories.
"""
from __future__ import annotations

import logging
from typing import Optional

from app.llm.client import get_llm_provider
from app.llm.prompts import REMEDIATION_PROMPT_VERSION, REMEDIATION_SYSTEM_PROMPT
from app.llm.provider import LLMProvider
from app.remediation.context_builder import RemediationContext
from app.remediation.patch_generator import apply_code_change, generate_unified_diff
from app.schemas.remediation import RemediationPlan

logger = logging.getLogger("ai_code_reviewer.remediation_agent")


class RemediationAgent:
    """
    Autonomous agent responsible for understanding defects and generating proposed fixes.
    """

    name: str = "Remediation Agent"
    agent_type: str = "remediation_agent"
    prompt_version: str = REMEDIATION_PROMPT_VERSION

    def __init__(self, llm_provider: Optional[LLMProvider] = None) -> None:
        self.llm_provider = llm_provider or get_llm_provider()

    async def generate_fix(self, context: RemediationContext) -> RemediationPlan:
        """
        Generate a structured RemediationPlan for the provided context.
        """
        prompt = self._build_prompt(context)

        logger.info(
            f"RemediationAgent generating fix for finding {context.finding_id[:8]} "
            f"({context.category}/{context.cwe or context.type})"
        )

        plan = await self.llm_provider.structured_output(
            prompt=prompt,
            schema_class=RemediationPlan,
            system=REMEDIATION_SYSTEM_PROMPT,
        )

        # If unified_diff was not generated by model, generate it deterministically
        if not plan.unified_diff and plan.changes:
            diffs = []
            for change in plan.changes:
                if change.file_path == context.file_path and context.file_content:
                    try:
                        modified_content = apply_code_change(
                            original_content=context.file_content,
                            start_line=change.start_line,
                            end_line=change.end_line,
                            original_code=change.original_code,
                            replacement_code=change.replacement_code,
                        )
                        diff = generate_unified_diff(
                            file_path=change.file_path,
                            original_content=context.file_content,
                            modified_content=modified_content,
                        )
                        diffs.append(diff)
                    except Exception as exc:
                        logger.warning(f"Failed to generate diff for change: {exc}")
            if diffs:
                plan.unified_diff = "\n".join(diffs)

        return plan

    def _build_prompt(self, ctx: RemediationContext) -> str:
        frameworks_str = ", ".join(ctx.frameworks) if ctx.frameworks else "None specified"
        dep_names = [d.get("name", "") for d in ctx.dependencies[:15] if isinstance(d, dict)]
        deps_str = ", ".join(dep_names) if dep_names else "Standard libraries"

        prompt_parts = [
            f"FINDING DETAILS:",
            f"- Title: {ctx.title}",
            f"- Category: {ctx.category}",
            f"- Type: {ctx.type or 'unspecified'}",
            f"- Severity: {ctx.severity}",
            f"- CWE: {ctx.cwe or 'N/A'}",
            f"- File: {ctx.file_path}",
            f"- Location: Lines {ctx.start_line} to {ctx.end_line}",
            f"- Language: {ctx.language}",
            f"- Frameworks: {frameworks_str}",
            f"- Key Dependencies: {deps_str}",
            f"- Description: {ctx.description}",
        ]

        if ctx.evidence:
            prompt_parts.append(f"\nDETECTED EVIDENCE:\n```\n{ctx.evidence}\n```")

        prompt_parts.append(f"\nSOURCE CODE CONTEXT (with line numbers):\n```\n{ctx.surrounding_code}\n```")

        # Retry feedback if previous attempt failed
        if ctx.previous_attempt:
            prompt_parts.append("\nPREVIOUS REMEDIATION ATTEMPT FAILED:")
            prompt_parts.append(f"- Previous Strategy: {ctx.previous_attempt.get('strategy', 'N/A')}")
            prompt_parts.append(f"- Verification Failure Reason: {ctx.previous_attempt.get('verification_reason', 'N/A')}")
            if ctx.previous_attempt.get('diff'):
                prompt_parts.append(f"- Previous Inadequate Diff:\n```\n{ctx.previous_attempt.get('diff')}\n```")
            prompt_parts.append("DO NOT repeat the previous flawed pattern. Address the root cause directly.")

        prompt_parts.append("\nINSTRUCTIONS:")
        prompt_parts.append("1. Provide the exact original code to replace from the source.")
        prompt_parts.append("2. Provide the clean, secure replacement code.")
        prompt_parts.append("3. Make the smallest necessary change to eliminate the issue safely.")

        return "\n".join(prompt_parts)
